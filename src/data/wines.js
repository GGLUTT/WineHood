const normalize = (value) => String(value).toLowerCase().trim();

// Пошук за назвою, виробником, країною, типом і смаком
export const searchWines = (query) => {
  const q = normalize(query);
  if (!q) return [];
  return allWines.filter((wine) =>
    [wine.name, wine.producer, wine.country, wine.type, wine.taste, wine.character]
      .some((field) => field && normalize(field).includes(q))
  );
};
